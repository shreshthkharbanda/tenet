#!/usr/bin/env python3
"""Inventory a repository: files, languages, LOC, tests, generated code,
entry-point hints, build/test hints, and a size tier.

Usage: inventory.py <repo_root> --out specs/_meta/inventory.json [--exclude GLOB ...]
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

from _common import SKIP_DIRS, eprint, glob_to_regex, rel, write_json

LANG_BY_EXT = {
    ".py": "python", ".pyi": "python", ".js": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".jsx": "javascript", ".ts": "typescript", ".tsx": "typescript", ".java": "java", ".kt": "kotlin",
    ".kts": "kotlin", ".go": "go", ".rs": "rust", ".rb": "ruby", ".php": "php", ".cs": "csharp",
    ".cpp": "cpp", ".cc": "cpp", ".cxx": "cpp", ".hpp": "cpp", ".c": "c", ".h": "c", ".swift": "swift",
    ".scala": "scala", ".sh": "shell", ".bash": "shell", ".zsh": "shell", ".sql": "sql", ".proto": "proto",
    ".graphql": "graphql", ".gql": "graphql", ".tf": "terraform", ".ex": "elixir", ".exs": "elixir",
    ".erl": "erlang", ".clj": "clojure", ".cljs": "clojure", ".hs": "haskell", ".ml": "ocaml",
    ".lua": "lua", ".dart": "dart", ".r": "r", ".m": "objc", ".mm": "objc", ".pl": "perl", ".vue": "vue",
    ".svelte": "svelte", ".zig": "zig", ".nim": "nim", ".jl": "julia", ".groovy": "groovy",
    ".yaml": "yaml", ".yml": "yaml", ".json": "json", ".toml": "toml", ".ini": "ini", ".cfg": "ini",
    ".env": "dotenv", ".properties": "properties", ".xml": "xml", ".md": "markdown", ".rst": "rst",
    ".txt": "text", ".html": "html", ".css": "css", ".scss": "css", ".csv": "csv",
}
CONFIG_LANGS = {"yaml", "json", "toml", "ini", "dotenv", "properties", "xml"}
DOC_LANGS = {"markdown", "rst", "text"}
DATA_LANGS = {"csv"}
SPECIAL_NAMES = {
    "Dockerfile": "dockerfile", "Makefile": "make", "Procfile": "procfile", "Jenkinsfile": "groovy",
    "Vagrantfile": "ruby", "Rakefile": "ruby", "Gemfile": "ruby", "CMakeLists.txt": "cmake",
}
TEST_DIR_PARTS = {"test", "tests", "__tests__", "spec", "specs", "testing", "e2e", "integration-tests"}
TEST_FILE_RE = re.compile(
    r"(^test_.*\.py$)|(_test\.(py|go|rb|rs|ex|exs)$)|(\.(test|spec)\.(js|jsx|ts|tsx|mjs)$)|(_spec\.rb$)",
    re.IGNORECASE,
)
# Case-sensitive on purpose: "UnboundedWait.java" must not match the "IT" suffix convention.
TEST_FILE_CS_RE = re.compile(r"(Test|Tests|IT|Spec)\.(java|kt|scala|cs|groovy)$|^Test[A-Z]\w*\.(java|kt)$")
SHEBANG_LANG = {"python": "python", "python3": "python", "bash": "shell", "sh": "shell", "zsh": "shell",
                "node": "javascript", "ruby": "ruby", "perl": "perl"}
GENERATED_PATH_RE = re.compile(r"(generated|\.pb\.|_pb2\.|\.min\.(js|css)$|\.d\.ts$|/gen/|/__generated__/)", re.IGNORECASE)
GENERATED_HEAD_RE = re.compile(r"(generated|do not edit|autogenerated|auto-generated)", re.IGNORECASE)

ENTRY_HINTS = [
    (re.compile(r"if\s+__name__\s*==\s*['\"]__main__['\"]"), "python main guard"),
    (re.compile(r"^\s*def\s+main\s*\("), "python main()"),
    (re.compile(r"@(app|router|api|bp|blueprint)\.(route|get|post|put|delete|patch)\("), "python http route"),
    (re.compile(r"\b(FastAPI|Flask|Sanic|Starlette)\("), "python web app"),
    (re.compile(r"@(click|typer)\.(command|group)|argparse\.ArgumentParser\("), "python cli"),
    (re.compile(r"\b(express|fastify|koa)\(\)|app\.listen\(|createServer\("), "node server"),
    (re.compile(r"\.(get|post|put|delete|patch)\(\s*['\"`]/"), "http route"),
    (re.compile(r"public\s+static\s+void\s+main\s*\("), "java main"),
    (re.compile(r"@(RestController|Controller|RequestMapping|GetMapping|PostMapping|Path|Mojo|SpringBootApplication)\b"), "java entry annotation"),
    (re.compile(r"^func\s+main\s*\(\)"), "go main"),
    (re.compile(r"http\.(HandleFunc|Handle)\(|\.(GET|POST|PUT|DELETE)\(\s*\""), "go http route"),
    (re.compile(r"^\s*(#\[tokio::main\]|fn\s+main\s*\()"), "rust main"),
    (re.compile(r"\b(Rails\.application\.routes|Sinatra|get\s+['\"]/)"), "ruby routes"),
    (re.compile(r"\bstatic\s+(async\s+)?(void|int|Task)\s+Main\s*\("), "csharp main"),
    (re.compile(r"\b(cron|schedule|@Scheduled|celery|BackgroundTasks|setInterval)\b"), "scheduled/background job"),
    (re.compile(r"\b(KafkaConsumer|@KafkaListener|SQS|subscribe\(|consumer\.(poll|run))"), "message consumer"),
]
BUILD_HINTS = {
    "pom.xml": "mvn -q test", "build.gradle": "gradle test", "build.gradle.kts": "gradle test",
    "package.json": "npm test (check scripts.test)", "pyproject.toml": "pytest", "setup.py": "pytest",
    "pytest.ini": "pytest", "tox.ini": "tox", "go.mod": "go test ./...", "Cargo.toml": "cargo test",
    "Gemfile": "bundle exec rspec", "mix.exs": "mix test", "Makefile": "make test (check targets)",
    "CMakeLists.txt": "ctest", "composer.json": "vendor/bin/phpunit", "Package.swift": "swift test",
    "build.sbt": "sbt test", "Dockerfile": "(container build)", "docker-compose.yml": "(compose stack)",
}


def list_files(root: Path, excludes: list[str]) -> list[Path]:
    files: list[Path] = []
    tracked: set[str] | None = None
    if (root / ".git").exists():
        try:
            out = subprocess.run(["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
                                 capture_output=True, check=True)
            tracked = {p for p in out.stdout.decode("utf-8", "replace").split("\0") if p}
        except Exception:
            tracked = None
    ex = [glob_to_regex(e) for e in excludes]
    if tracked is not None:
        cands = sorted(tracked)
    else:
        cands = []
        for dp, dns, fns in __import__("os").walk(root):
            dns[:] = [d for d in dns if d not in SKIP_DIRS and not d.startswith(".")]
            for fn in fns:
                cands.append(rel(Path(dp) / fn, root))
        cands.sort()
    for p in cands:
        parts = p.split("/")
        if any(part in SKIP_DIRS for part in parts[:-1]):
            continue
        if any(r.match(p) for r in ex):
            continue
        fp = root / p
        if fp.is_file() and not fp.is_symlink():
            files.append(fp)
    return files


def is_binary(fp: Path) -> bool:
    try:
        with open(fp, "rb") as f:
            chunk = f.read(2048)
        return b"\0" in chunk
    except OSError:
        return True


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("repo")
    ap.add_argument("--out", required=True)
    ap.add_argument("--exclude", action="append", default=[], help="glob to exclude (repeatable)")
    ap.add_argument("--include", action="append", default=[],
                    help="glob to keep in scope (repeatable). Files outside every --include stay in the inventory "
                         "(callers and tests are context) but are marked in_scope=false and never sharded.")
    ap.add_argument("--max-bytes", type=int, default=2_000_000)
    args = ap.parse_args()
    root = Path(args.repo).resolve()
    excludes = list(args.exclude) + ["specs/**", "**/.claude/**"]
    include_rx = [glob_to_regex(g) for g in args.include]

    records = []
    by_lang: dict[str, dict] = {}
    by_top: dict[str, dict] = {}
    entry_hints = []
    build_hints = {}
    total_loc = 0
    source_loc = 0
    for fp in list_files(root, excludes):
        p = rel(fp, root)
        name = fp.name
        size = fp.stat().st_size
        lang = SPECIAL_NAMES.get(name) or LANG_BY_EXT.get(fp.suffix.lower(), "")
        if not lang and not fp.suffix and size < args.max_bytes:
            try:
                with open(fp, "rb") as fh:
                    first = fh.readline(200).decode("utf-8", "replace")
                if first.startswith("#!"):
                    interp = re.sub(r".*/", "", first.strip().split()[-1] if "env" in first else first.strip().split()[0])
                    lang = SHEBANG_LANG.get(interp, "shell")
            except OSError:
                pass
        if name in BUILD_HINTS:
            build_hints.setdefault(p, BUILD_HINTS[name])
        if not lang or size > args.max_bytes or is_binary(fp):
            records.append({"path": p, "lang": lang or "binary/unknown", "kind": "other", "loc": 0, "lines": 0,
                            "bytes": size, "is_test": False, "is_generated": False, "in_scope": False})
            continue
        try:
            text = fp.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        lines = text.splitlines()
        loc = sum(1 for ln in lines if ln.strip())
        if lang in CONFIG_LANGS:
            kind = "config"
        elif lang in DOC_LANGS:
            kind = "doc"
        elif lang in DATA_LANGS:
            kind = "data"
        else:
            kind = "source"
        parts = p.split("/")
        is_test = (bool(TEST_FILE_RE.search(name)) or bool(TEST_FILE_CS_RE.search(name))
                   or any(part.lower() in TEST_DIR_PARTS for part in parts[:-1]))
        head = "\n".join(lines[:5])
        is_generated = bool(GENERATED_PATH_RE.search(p)) or bool(GENERATED_HEAD_RE.search(head))
        if kind == "source" and not is_test and not is_generated and ((not include_rx) or any(rx.match(p) for rx in include_rx)):
            for rx, label in ENTRY_HINTS:
                if rx.search(text):
                    entry_hints.append({"path": p, "hint": label})
                    break
        scoped = (not include_rx) or any(rx.match(p) for rx in include_rx)
        rec = {"path": p, "lang": lang, "kind": kind, "loc": loc, "lines": len(lines), "bytes": size,
               "is_test": is_test, "is_generated": is_generated, "in_scope": scoped}
        records.append(rec)
        total_loc += loc
        if kind == "source" and not is_test and not is_generated and scoped:
            source_loc += loc
        bl = by_lang.setdefault(lang, {"files": 0, "loc": 0})
        bl["files"] += 1
        bl["loc"] += loc
        top = parts[0] if len(parts) > 1 else "(root)"
        bt = by_top.setdefault(top, {"files": 0, "loc": 0, "source_loc": 0})
        bt["files"] += 1
        bt["loc"] += loc
        if kind == "source" and not is_test and not is_generated and scoped:
            bt["source_loc"] += loc

    tier = "S" if source_loc < 15_000 else "M" if source_loc < 150_000 else "L"
    summary = {
        "repo_root": str(root),
        "total_files": len(records),
        "total_loc": total_loc,
        "source_loc_in_scope": source_loc,
        "tier": tier,
        "tier_rule": "S < 15k in-scope source LOC; M < 150k; L otherwise",
        "by_language": dict(sorted(by_lang.items(), key=lambda kv: -kv[1]["loc"])),
        "by_top_dir": dict(sorted(by_top.items(), key=lambda kv: -kv[1]["loc"])),
        "test_files": sum(1 for r in records if r["is_test"]),
        "generated_files": sum(1 for r in records if r["is_generated"]),
        "excludes": excludes,
        "includes": args.include,
        "largest_in_scope_files": sorted(
            [{"path": r["path"], "lines": r["lines"], "loc": r["loc"]} for r in records
             if r["kind"] == "source" and not r["is_test"] and not r["is_generated"] and r.get("in_scope")],
            key=lambda r: -r["loc"])[:15],
    }
    out = {"summary": summary, "build_hints": build_hints, "entry_hints": entry_hints, "files": records}
    write_json(Path(args.out), out)
    eprint(f"inventory: {len(records)} files, {source_loc} in-scope source LOC, tier {tier}, "
           f"{len(entry_hints)} entry hints -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
